import { z } from "zod";
import {
  adminProductValuesSchema,
  editedShelfCountSchema,
  keepsNegativeShelfOnly,
  NEGATIVE_STOCK_MESSAGE,
  openedShelfCountSchema,
} from "../schemas/admin-suppliers.ts";
import { freeText, pageNumberSchema, searchQuery } from "../schemas/common.ts";
import { refuseSupplierTextContact } from "../schemas/contact-guard.ts";
import { optionalParameter, withFallback } from "../schemas/fallback.ts";
import {
  PRODUCT_REVIEW_STATUSES,
  rejectionReasonsSchema,
} from "./supplier-panel-catalog-status.ts";
import { supplierImageUrlsSchema } from "./supplier-panel-image-urls.ts";

/** Every input carries the supplier explicitly; the access layer fills it from the session. */
const supplierScopeSchema = z.object({ supplierId: z.uuid() });

export const CATALOG_SORT_COLUMNS = ["title", "sku", "stock", "costCents", "updatedAt"] as const;
export type CatalogSortColumn = (typeof CATALOG_SORT_COLUMNS)[number];
export const CATALOG_STATUS_FILTERS = ["all", ...PRODUCT_REVIEW_STATUSES] as const;
export type CatalogStatusFilter = (typeof CATALOG_STATUS_FILTERS)[number];

/** List filters as they come from the URL: anything malformed falls back to the default. */
export const catalogListSearchSchema = z.object({
  status: withFallback(z.enum(CATALOG_STATUS_FILTERS).default("all"), "all"),
  query: optionalParameter(searchQuery()),
  sort: withFallback(z.enum(CATALOG_SORT_COLUMNS).default("updatedAt"), "updatedAt"),
  direction: withFallback(z.enum(["asc", "desc"]).default("desc"), "desc"),
  page: withFallback(pageNumberSchema.default(1), 1),
  pageSize: withFallback(z.coerce.number().int().min(10).max(100).default(25), 25),
});
export type CatalogListSearch = z.infer<typeof catalogListSearchSchema>;
export const catalogListInputSchema = supplierScopeSchema.extend(catalogListSearchSchema.shape);

/**
 * A draft may be incomplete: only the SKU is needed to store it (it is the product's key for
 * the supplier). Everything else reuses the admin form's validation, so both forms agree, except
 * photos, which must be https for the supplier (staff may still save http links).
 */
export const catalogDraftValuesSchema = adminProductValuesSchema.extend({
  title: freeText().trim().max(300).superRefine(refuseSupplierTextContact),
  stock: editedShelfCountSchema,
  imageUrls: supplierImageUrlsSchema,
});
export type CatalogDraftValues = z.infer<typeof catalogDraftValuesSchema>;

export const catalogSaveDraftSchema = supplierScopeSchema
  .extend({
    /** Generated by the form before the first save, so a retried autosave never duplicates. */
    productId: z.uuid(),
    values: catalogDraftValuesSchema,
    /** `updatedAt` the form last saw; absent only for a product that was never saved. */
    expectedUpdatedAt: z.iso.datetime({ offset: true }).optional(),
    /** Shelf count the form was opened with; sales may have moved it since (admin form rule). */
    expectedStock: openedShelfCountSchema.optional(),
  })
  .refine((input) => keepsNegativeShelfOnly(input.values.stock, input.expectedStock), {
    path: ["values", "stock"],
    error: NEGATIVE_STOCK_MESSAGE,
  });
export type CatalogSaveDraftInput = z.infer<typeof catalogSaveDraftSchema>;

export const catalogProductRefSchema = supplierScopeSchema.extend({ productId: z.uuid() });
export type CatalogProductRef = z.infer<typeof catalogProductRefSchema>;

export const catalogRejectSchema = catalogProductRefSchema.extend({
  reasons: rejectionReasonsSchema,
});
export type CatalogRejectInput = z.infer<typeof catalogRejectSchema>;
